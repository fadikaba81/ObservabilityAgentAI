package output

import (
	"fmt"
	"net/smtp"
	"strings"
	"time"

	"github.com/fadikaba81/ObservabilityAgentAI/internal/reasoner"
)

// Mailer sends plain-text email over SMTP. smtp.SendMail upgrades to STARTTLS
// when the server offers it, which covers port 587 relays.
type Mailer struct {
	host     string
	port     int
	username string
	password string
	from     string
	to       []string
}

// NewMailer takes a comma-separated list of recipients in to.
func NewMailer(host string, port int, username, password, from, to string) *Mailer {
	var recipients []string
	for _, addr := range strings.Split(to, ",") {
		if a := strings.TrimSpace(addr); a != "" {
			recipients = append(recipients, a)
		}
	}
	return &Mailer{
		host:     host,
		port:     port,
		username: username,
		password: password,
		from:     from,
		to:       recipients,
	}
}

func (m *Mailer) Send(subject, body string) error {
	if len(m.to) == 0 {
		return fmt.Errorf("no recipients configured")
	}

	var auth smtp.Auth
	if m.username != "" {
		auth = smtp.PlainAuth("", m.username, m.password, m.host)
	}

	msg := strings.Join([]string{
		"From: " + m.from,
		"To: " + strings.Join(m.to, ", "),
		"Subject: " + subject,
		"Date: " + time.Now().Format(time.RFC1123Z),
		"MIME-Version: 1.0",
		"Content-Type: text/plain; charset=UTF-8",
		"",
		body,
	}, "\r\n")

	return smtp.SendMail(fmt.Sprintf("%s:%d", m.host, m.port), auth, m.from, m.to, []byte(msg))
}

// RenderReport builds the email subject and plain-text body for an analysis.
func RenderReport(alertName, service string, start, end time.Time, a *reasoner.Analysis, warnings []string) (string, string) {
	subject := fmt.Sprintf("[SRE Agent] %s: %s", service, alertName)

	var sb strings.Builder
	fmt.Fprintf(&sb, "Service: %s\n", service)
	fmt.Fprintf(&sb, "Alert: %s\n", alertName)
	fmt.Fprintf(&sb, "Window: %s to %s (UTC)\n", start.UTC().Format(time.RFC3339), end.UTC().Format(time.RFC3339))
	fmt.Fprintf(&sb, "Confidence: %s\n\n", a.Confidence)

	fmt.Fprintf(&sb, "SUMMARY\n%s\n\n", a.Summary)
	fmt.Fprintf(&sb, "PROBABLE ROOT CAUSE\n%s\n\n", a.ProbableRootCause)

	sb.WriteString("EVIDENCE\n")
	for _, e := range a.Evidence {
		fmt.Fprintf(&sb, "- %s\n", e)
	}

	sb.WriteString("\nRECOMMENDED ACTIONS\n")
	for i, r := range a.RecommendedActions {
		fmt.Fprintf(&sb, "%d. %s\n", i+1, r)
	}

	if len(warnings) > 0 {
		sb.WriteString("\nDATA COLLECTION WARNINGS\n")
		for _, w := range warnings {
			fmt.Fprintf(&sb, "- %s\n", w)
		}
	}

	sb.WriteString("\n--\nGenerated by ObservabilityAgentAI. Verify before acting.\n")
	return subject, sb.String()
}
